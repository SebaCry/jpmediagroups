/* ----------------------------------------------------------- page records */

export interface PageSeo {
  /** Under ~60 characters so it is not truncated in the result. */
  title: string;
  /** 140–160 characters, written to earn the click, not to stuff terms. */
  description: string;
  /** Path-relative share card. Falls back to the default. */
  image?: string;
  imageAlt?: string;
  type?: 'website' | 'article' | 'profile';
  /** Keeps a page out of the index without keeping crawlers off it. */
  noindex?: boolean;
  /** Trail shown in the result, home excluded — it is added automatically. */
  breadcrumbs?: Array<{ name: string; path: string }>;
  /** Extra schema nodes merged into the page graph. */
  schema?: Record<string, unknown>[];
}

