/**
 * The breadcrumb trail. Home is prepended here so no page has to repeat it,
 * and the current page is included as the last item — Google drops trails that
 * do not terminate on the page they are served from.
 */
export function breadcrumbs(
  trail: Array<{ name: string; path: string }>,
  url: string,
): Record<string, unknown> | null {
  if (!trail.length) return null;
  const items = [{ name: 'Home', path: '/' }, ...trail];
  return {
    '@type': 'BreadcrumbList',
    '@id': `${url}#breadcrumb`,
    itemListElement: items.map((item, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: item.name,
      item: abs(item.path),
    })),
  };
}

export function webPage(page: PageSeo, url: string): Record<string, unknown> {
  const node: Record<string, unknown> = {
    '@type': 'WebPage',
    '@id': `${url}#webpage`,
    url,
    name: page.title,
    description: page.description,
    isPartOf: { '@id': ID.website },
    about: { '@id': ID.org },
    primaryImageOfPage: { '@id': ID.logo },
    inLanguage: LANG,
  };
  if (page.breadcrumbs?.length) node.breadcrumb = { '@id': `${url}#breadcrumb` };
  return node;
}

/**
 * Assembles the page's whole graph as ONE script tag.
 *
 * A single `@graph` is deliberate. Multiple separate JSON-LD blocks are legal,
 * but nodes in different blocks cannot reference each other by @id, so the
 * Organization, the page and the breadcrumb end up as three unrelated islands.
 */
export function jsonLd(page: PageSeo, url: string): string {
  const graph = [
    organization(),
    logoNode(),
    website(),
    webPage(page, url),
    breadcrumbs(page.breadcrumbs ?? [], url),
    ...(page.schema ?? []),
  ].filter(Boolean);

  return JSON.stringify({ '@context': 'https://schema.org', '@graph': graph });
}

